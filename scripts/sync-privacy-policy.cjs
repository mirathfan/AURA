// Keep the standalone website deployment and repository policy in sync with
// the disclosure bundled into the app. No network or publishing operations.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'shared/privacyPolicy.ts'), 'utf8');
const context = { exports: {} };
vm.runInNewContext(ts.transpile(source, { module: ts.ModuleKind.CommonJS }), context);
const { PRIVACY_UPDATED, PRIVACY_SECTIONS } = context.exports;
const outputs = {
  'website/lib/privacyPolicy.ts': '// Generated by scripts/sync-privacy-policy.cjs. Edit shared/privacyPolicy.ts.\n' + source,
  'PRIVACY_POLICY.md': '# AURA Privacy Policy\n\nUpdated ' + PRIVACY_UPDATED + '.\n\n' + PRIVACY_SECTIONS.map(({ title, text }) => '## ' + title + '\n\n' + text).join('\n\n') + '\n',
};
for (const [filename, text] of Object.entries(outputs)) {
  const destination = path.join(root, filename);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8') !== text) throw new Error('Privacy policy is out of sync: ' + filename);
  } else fs.writeFileSync(destination, text);
}
console.log('Privacy policy copies are synchronized.');
